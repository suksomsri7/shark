/**
 * คีย์ที่อนุญาตให้ออกไปนอกบ้านได้เท่านั้น (PDPA · WO-CV9 ข้อ 4)
 *
 * 🔴 นี่คือ **บัญชีขาว** ไม่ใช่บัญชีดำ — เพราะบัญชีดำต้องเดาชื่อฟิลด์ในอนาคตให้ถูกทุกตัว
 *    วันหนึ่งใครเผลอส่ง `body`/`preview`/`customerName` มา ของพวกนั้นจะถูกทิ้งเงียบ ๆ ที่นี่
 *    โดยที่ผู้ให้บริการไม่มีวันได้เห็น · ผู้ให้บริการรู้ได้แค่ "ร้านไหน ห้องไหน มีของใหม่เมื่อไหร่"
 */
export const SAFE_KEYS = ["conversationId", "userId", "kind", "until", "at"] as const;

/** ค่าที่เป็น "ตัวชี้" (id/ชนิด) ต้องหน้าตาแบบนี้เท่านั้น — กันคนแอบยัดประโยคมาในช่อง id */
const ID_RE = /^[A-Za-z0-9_.:-]{1,64}$/;

export type Signal = {
  conversationId?: string;
  userId?: string;
  kind?: string;
  until?: number;
  at?: number;
};

/**
 * คัดกรองสิ่งที่จะออกไปนอกบ้าน — เรียกที่ **ขอบ** (ใน `publish`) ไม่ใช่ฝากความหวังไว้กับผู้เรียก
 *
 * 🔴 เหตุผลที่กรองที่ขอบ: จุดยิงสัญญาณมีหลายที่ (ขาเข้า 3 เส้น · ทีมตอบ 2 เส้น · อ่านแล้ว · พิมพ์อยู่)
 *    ถ้ากรองที่ผู้เรียก แปลว่าต้องถูกทั้ง 7 ที่ตลอดไป · กรองที่ขอบ = ผิดที่ผู้เรียกก็ยังไม่รั่ว
 */
export function sanitizeSignal(payload: unknown): Signal {
  const src = payload !== null && typeof payload === "object" && !Array.isArray(payload)
    ? (payload as Record<string, unknown>)
    : {};
  const out: Signal = {};
  for (const k of SAFE_KEYS) {
    const v = src[k];
    if (k === "until" || k === "at") {
      if (typeof v === "number" && Number.isFinite(v)) out[k] = Math.trunc(v);
      continue;
    }
    if (typeof v === "string" && ID_RE.test(v)) out[k] = v;
  }
  // เวลาที่สัญญาณเกิด — จอใช้ตัดสินว่าของเก่าค้างท่อหรือเปล่า (ไม่มีข้อมูลลูกค้าอยู่ในนี้)
  if (out.at === undefined) out.at = Date.now();
  return out;
}
