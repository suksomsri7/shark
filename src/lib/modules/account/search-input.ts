/** ความยาวสูงสุดของคำค้นในทุกหน้ารายการ/ตัวเลือกของโมดูลบัญชี */
export const MAX_SEARCH_LEN = 200;

/**
 * ตัดคำค้นให้อยู่ในขอบเขต (trim + จำกัด 200 ตัว) — **ทุกจุดที่รับ `q` จากผู้ใช้ต้องผ่านตัวนี้**
 *
 * 🔴 ทำไม: `q` ถูกส่งต่อเป็น `contains` ของ Postgres (ILIKE) โดยไม่มีเพดานความยาวเลย
 *    ยิงคำค้นยาวเป็นแสนตัวใส่หลายคอลัมน์พร้อมกัน = ให้ DB ทำงานหนักฟรี ๆ ต่อ 1 request
 *    (ไม่ใช่ SQL injection — Prisma ผูกค่าให้อยู่แล้ว — แต่เป็นการเปิดทางถล่มด้วยต้นทุนต่ำ)
 */
export function clampSearch(q: string | null | undefined): string {
  return String(q ?? "").trim().slice(0, MAX_SEARCH_LEN);
}
